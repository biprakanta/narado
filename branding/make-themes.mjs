#!/usr/bin/env node
/**
 * Generates narado's light and dark themes from Bruno's own (packages/bruno-app/src/themes):
 *   1. copies light.js / dark.js,
 *   2. replaces the palette blocks with narado's brand palette (branding/README.md),
 *   3. tints every remaining neutral grey: warm cream in light, plum in dark.
 * Re-run after merging upstream Bruno so the narado themes pick up new theme keys:
 *   node branding/make-themes.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const themesDir = path.join(root, 'packages/bruno-app/src/themes');

const BRAND = {
  light: {
    primary: { SOLID: '#E8590C', TEXT: '#C2410C', STRONG: '#D9480F', SUBTLE: '#FB9B1A' },
    system: { CONTROL_ACCENT: '#E8590C' },
    background: { BASE: '#FFFFFF', MANTLE: '#FCF8F2', CRUST: '#F9F3EA', SURFACE0: '#F4ECE0', SURFACE1: '#EDE3D4', SURFACE2: '#E4D8C6' },
    text: { BASE: '#2A1F33', SUBTEXT2: '#5E5267', SUBTEXT1: '#7A6F82', SUBTEXT0: '#958B9C' },
    border: { BORDER3: '#C9BBAA', BORDER2: '#DDD0BF', BORDER1: '#EBE1D3', BORDER0: '#F3ECE2' }
  },
  dark: {
    primary: { SOLID: '#FB9B1A', TEXT: '#FDB55A', STRONG: '#FDB55A', SUBTLE: '#FD6E15' },
    system: { CONTROL_ACCENT: '#FB9B1A' },
    background: { BASE: '#17121F', MANTLE: '#1D1726', CRUST: '#140F1B', SURFACE0: '#241D2F', SURFACE1: '#30283C', SURFACE2: '#5D5468' },
    text: { BASE: '#EDE4D8', SUBTEXT2: '#C7BCCB', SUBTEXT1: '#ADA2B3', SUBTEXT0: '#958A9B' },
    border: { BORDER3: '#5D5468', BORDER2: '#463D52', BORDER1: '#342B40', BORDER0: '#271F31' }
  }
};

const hex2rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const rgb2hex = (rgb) => '#' + rgb.map((v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0')).join('');
const hsl2rgb = (h, s, l) => {
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  return [0, 8, 4].map((n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1))));
};

/** A neutral grey (channels within 6/255) becomes a tinted colour of the same lightness. */
const tint = (mode) => (hex) => {
  const rgb = hex2rgb(hex);
  if (Math.max(...rgb) - Math.min(...rgb) > 6 / 255) return hex;
  const l = (Math.max(...rgb) + Math.min(...rgb)) / 2;
  if (l === 0 || l === 1) return hex; // keep pure black and white
  if (mode === 'dark') return rgb2hex(hsl2rgb(275, l < 0.5 ? 0.24 : 0.14, l));
  return rgb2hex(l > 0.6 ? hsl2rgb(36, 0.32, l) : hsl2rgb(280, 0.14, l));
};

const block = (name, values) =>
  `  ${name}: {\n${Object.entries(values).map(([k, v]) => `    ${k}: '${v}'`).join(',\n')}\n  }`;

const make = (mode) => {
  const src = fs.readFileSync(path.join(themesDir, mode, `${mode}.js`), 'utf8');
  let out = src;
  for (const [name, values] of Object.entries(BRAND[mode])) {
    const re = new RegExp(`  ${name}: \\{[^}]*\\}`);
    if (!re.test(out)) throw new Error(`${mode}.js has no palette block "${name}"`);
    out = out.replace(re, block(name, values));
  }
  out = out.replace(/#[0-9a-fA-F]{6}\b/g, (h) => (Object.values(BRAND[mode]).some((b) => Object.values(b).includes(h)) ? h : tint(mode)(h)));
  out = out.replace(/const (light|dark)Theme = \{/, `const narado${mode === 'light' ? 'Light' : 'Dark'}Theme = {`)
    .replace(/export default (light|dark)Theme;/, `export default narado${mode === 'light' ? 'Light' : 'Dark'}Theme;`);
  const header = `// Generated by branding/make-themes.mjs from ${mode}/${mode}.js. Do not edit by hand; change the script and re-run it.\n`;
  const file = path.join(themesDir, 'narado', `narado-${mode}.js`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, header + out);
  console.log('wrote', path.relative(root, file));
};

make('light');
make('dark');
